// Command results runs the performance criteria several times through the
// acceptance tests and writes bench/RESULTS.md with the median and min-max
// of each measurement.
package main

import (
	"context"
	"encoding/json"
	"errors"
	"flag"
	"fmt"
	"os"
	"os/exec"
	"path/filepath"
	"runtime"
	"slices"
	"strconv"
	"strings"
	"time"
)

type scenario struct {
	id, name, test string
	bench          bool
	// metrics are the measured keys reported, with their threshold key and
	// whether larger is better.
	metrics []metric
}

type metric struct {
	key, label, threshold string
	higherIsBetter        bool
}

var scenarios = []scenario{
	{id: "FMN-04", name: "Throughput", test: "BenchmarkAcceptance_FMN04_Throughput", bench: true, metrics: []metric{
		{"throughput_jobs_per_s", "throughput (jobs/s)", "throughput_min_jobs_per_s", true},
		{"fair_throughput_jobs_per_s", "throughput with fairness, 1,000 keys, limit 50 (jobs/s)", "", true},
	}},
	{id: "FMN-05", name: "Pickup latency", test: "BenchmarkAcceptance_FMN05_PickupLatency", bench: true, metrics: []metric{
		{"p99_ms", "pickup latency p99 (ms)", "p99_ms_max", false},
		{"p50_ms", "pickup latency p50 (ms)", "", false},
	}},
	{id: "FMN-06", name: "Fairness", test: "TestAcceptance_FMN06_Fairness", metrics: []metric{
		{"b_p95_fair_ms", "small tenant p95 wait, fair (ms)", "", false},
		{"b_p95_unfair_ms", "small tenant p95 wait, unfair (ms)", "", false},
		{"b_p95_alone_ms", "small tenant p95 wait, alone (ms)", "", false},
	}},
	{id: "FMN-12", name: "Soak", test: "TestAcceptance_FMN12_Soak", metrics: []metric{
		{"size_drift", "table + index size drift (fraction)", "size_drift_max", false},
		{"p99_drift", "p99 latency drift (fraction)", "p99_drift_max", false},
		{"p99_end_ms", "p99 pickup latency at the end (ms)", "", false},
	}},
}

func main() {
	runs := flag.Int("runs", 3, "runs per scenario")
	version := flag.String("version", "dev", "Foreman version shown with each result")
	only := flag.String("only", "", "comma-separated scenario ids")
	out := flag.String("out", "bench/RESULTS.md", "output file")
	flag.Parse()
	if err := run(*runs, *only, *out, *version); err != nil {
		fmt.Fprintln(os.Stderr, "results:", err)
		os.Exit(1)
	}
}

func run(runs int, only, out, version string) error {
	ctx := context.Background()
	if err := compose(ctx, "up", "-d", "--wait"); err != nil {
		return fmt.Errorf("compose up: %w", err)
	}
	defer func() { _ = compose(context.WithoutCancel(ctx), "down", "-v") }()
	logDir, err := filepath.Abs("out/bench")
	if err != nil {
		return err
	}
	if err := os.MkdirAll(logDir, 0o750); err != nil {
		return err
	}
	var sections []string
	for _, s := range scenarios {
		if only != "" && !slices.Contains(strings.Split(only, ","), s.id) {
			continue
		}
		var results []map[string]any
		var thresholds map[string]any
		for i := 1; i <= runs; i++ {
			fmt.Printf("%s run %d/%d\n", s.id, i, runs)
			res, th, err := runOnce(ctx, s, logDir, i)
			if err != nil {
				return fmt.Errorf("%s run %d: %w", s.id, i, err)
			}
			results = append(results, res)
			thresholds = th
		}
		sections = append(sections, render(s, version, results, thresholds))
	}
	header := "# Benchmark results\n\nGenerated by `make bench` (bench/cmd/results); each scenario is an acceptance\n" +
		"criterion run " + strconv.Itoa(runs) + " times. Raw results: out/bench/.\n"
	return os.WriteFile(out, []byte(header+"\n"+strings.Join(sections, "\n")), 0o600)
}

func compose(ctx context.Context, args ...string) error {
	args = append([]string{"compose", "-f", "deploy/docker-compose.yml"}, args...)
	return exec.CommandContext(ctx, "docker", args...).Run() //nolint:gosec // G204: fixed arguments from this program
}

func runOnce(ctx context.Context, s scenario, logDir string, n int) (map[string]any, map[string]any, error) {
	args := []string{"test", "-tags", "acceptance", "-count=1", "-timeout", "3h"}
	if s.bench {
		args = append(args, "-run", "^$", "-bench", "^"+s.test+"$", "-benchtime", "1x")
	} else {
		args = append(args, "-run", "^"+s.test+"$")
	}
	args = append(args, "./acceptance/...")
	cmd := exec.CommandContext(ctx, "go", args...)
	cmd.Env = append(os.Environ(), "FOREMAN_ACC_LOG_DIR="+logDir)
	output, err := cmd.CombinedOutput()
	if werr := os.WriteFile(filepath.Join(logDir, fmt.Sprintf("%s-run%d.txt", s.id, n)), output, 0o600); werr != nil {
		return nil, nil, werr
	}
	if err != nil {
		return nil, nil, fmt.Errorf("go test: %w (see out/bench)", err)
	}
	data, err := os.ReadFile(filepath.Join(logDir, s.id+".json")) //nolint:gosec // G304: fixed results directory
	if err != nil {
		return nil, nil, err
	}
	runFile := filepath.Join(logDir, fmt.Sprintf("%s-run%d.json", s.id, n))
	if err := os.WriteFile(runFile, data, 0o600); err != nil { //nolint:gosec // G703: fixed results directory
		return nil, nil, err
	}
	var res struct {
		Measured map[string]any `json:"measured"`
		Pass     bool           `json:"pass"`
		Details  map[string]any `json:"details"`
	}
	if err := json.Unmarshal(data, &res); err != nil {
		return nil, nil, err
	}
	if !res.Pass {
		return nil, nil, errors.New("criterion failed")
	}
	return res.Measured, thresholdsOf(s.id), nil
}

func thresholdsOf(id string) map[string]any {
	data, err := os.ReadFile("acceptance/criteria.yaml")
	if err != nil {
		return nil
	}
	// Minimal lookup of "key: value" lines under the criterion's mac block.
	out := map[string]any{}
	in, mac := false, false
	for _, line := range strings.Split(string(data), "\n") {
		trimmed := strings.TrimSpace(line)
		switch {
		case strings.HasPrefix(trimmed, "- id: "):
			in = strings.TrimPrefix(trimmed, "- id: ") == id
			mac = false
		case in && strings.HasPrefix(trimmed, "mac:"):
			mac = true
		case in && strings.HasPrefix(trimmed, "ci:"):
			mac = false
		case in && mac && strings.Contains(trimmed, ": "):
			k, v, _ := strings.Cut(trimmed, ": ")
			out[k] = v
		}
	}
	return out
}

func render(s scenario, version string, results []map[string]any, th map[string]any) string {
	var b strings.Builder
	fmt.Fprintf(&b, "## %s (%s) — %s\n", s.name, s.id, time.Now().UTC().Format("2006-01-02"))
	fmt.Fprintf(&b, "Machine: MacBook Pro M3 Pro 36 GB, macOS %s, Docker VM 8 CPU / 20 GB, Go %s, Foreman %s\n\n",
		macOSVersion(), strings.TrimPrefix(runtime.Version(), "go"), version)
	b.WriteString("| Metric | Median | Min | Max | Threshold | Pass |\n|---|---|---|---|---|---|\n")
	for _, m := range s.metrics {
		var vals []float64
		for _, r := range results {
			if v, ok := r[m.key].(float64); ok {
				vals = append(vals, v)
			}
		}
		if len(vals) == 0 {
			continue
		}
		slices.Sort(vals)
		median := vals[len(vals)/2]
		threshold, pass := thresholdCell(m, th, median)
		fmt.Fprintf(&b, "| %s | %s | %s | %s | %s | %s |\n", m.label, num(median), num(vals[0]), num(vals[len(vals)-1]),
			threshold, pass)
	}
	return b.String()
}

// thresholdCell renders the threshold of m and whether median meets it.
func thresholdCell(m metric, th map[string]any, median float64) (threshold, pass string) {
	t, ok := th[m.threshold]
	if m.threshold == "" || !ok {
		return "reported", "—"
	}
	var tv float64
	_, _ = fmt.Sscan(fmt.Sprint(t), &tv)
	met := median <= tv
	threshold = fmt.Sprintf("<= %v", t)
	if m.higherIsBetter {
		met = median >= tv
		threshold = fmt.Sprintf(">= %v", t)
	}
	return threshold, map[bool]string{true: "yes", false: "no"}[met]
}

func num(v float64) string {
	switch {
	case v >= 1000:
		return fmt.Sprintf("%.0f", v)
	case v >= 10:
		return fmt.Sprintf("%.1f", v)
	default:
		return fmt.Sprintf("%.3f", v)
	}
}

func macOSVersion() string {
	out, err := exec.CommandContext(context.Background(), "sw_vers", "-productVersion").Output()
	if err != nil {
		return "unknown"
	}
	return strings.TrimSpace(string(out))
}
